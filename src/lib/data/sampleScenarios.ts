/**
 * Deterministically generates a plan from natural language specifications
 * when no API key is provided or as instant fallback.
 */
export function generateDeterministicPlan(req: ParsedNLRequest): FullEventPlan {
  const eventId = crypto.randomUUID();
  const eventDate = new Date();
  eventDate.setDate(eventDate.getDate() + (req.daysUntilEvent || 45));
  const eventDateStr = eventDate.toISOString().split('T')[0];

  const total = req.budgetTotal;
  const contingency = Math.round(total * 0.10); // 10% safety buffer
  const spendable = total - contingency;

  let categories = [];
  if (req.eventType === 'wedding') {
    categories = [
      { id: crypto.randomUUID(), eventId, name: 'Venue & Banquet Hall', allocatedAmount: Math.round(spendable * 0.35), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Catering & Dining Feast', allocatedAmount: Math.round(spendable * 0.30), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Floral Stage & Lighting Decor', allocatedAmount: Math.round(spendable * 0.15), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Photography & Cinematography', allocatedAmount: Math.round(spendable * 0.12), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Music, Sound & Logistics', allocatedAmount: Math.round(spendable * 0.08), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Contingency Reserve (10%)', allocatedAmount: contingency, spentAmount: 0, isContingency: true },
    ];
  } else if (req.eventType === 'birthday') {
    categories = [
      { id: crypto.randomUUID(), eventId, name: 'Venue & Party Space', allocatedAmount: Math.round(spendable * 0.35), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Food, Drinks & Birthday Cake', allocatedAmount: Math.round(spendable * 0.35), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Themed Decor & Balloon Styling', allocatedAmount: Math.round(spendable * 0.15), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Entertainment, Emcee & Games', allocatedAmount: Math.round(spendable * 0.15), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Contingency Reserve (10%)', allocatedAmount: contingency, spentAmount: 0, isContingency: true },
    ];
  } else {
    categories = [
      { id: crypto.randomUUID(), eventId, name: 'Stage, AV & Equipment', allocatedAmount: Math.round(spendable * 0.35), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Logistics, Stalls & Power', allocatedAmount: Math.round(spendable * 0.30), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Permits, Safety & Security', allocatedAmount: Math.round(spendable * 0.20), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Signage & Promotion', allocatedAmount: Math.round(spendable * 0.15), spentAmount: 0, isContingency: false },
      { id: crypto.randomUUID(), eventId, name: 'Contingency Reserve (10%)', allocatedAmount: contingency, spentAmount: 0, isContingency: true },
    ];
  }

  // Generate milestone tasks with valid non-circular dependencies
  const t1Id = crypto.randomUUID();
  const t2Id = crypto.randomUUID();
  const t3Id = crypto.randomUUID();
  const t4Id = crypto.randomUUID();

  const d1 = new Date();
  d1.setDate(d1.getDate() + 7);
  const d2 = new Date();
  d2.setDate(d2.getDate() + 15);
  const d3 = new Date();
  d3.setDate(d3.getDate() + 25);
  const d4 = new Date();
  d4.setDate(d4.getDate() + (req.daysUntilEvent - 3));

  const tasks = [
    {
      id: t1Id,
      eventId,
      name: `Secure and Contract Primary ${req.eventType === 'wedding' ? 'Kalyana Mandapam' : 'Venue'} in ${req.location}`,
      description: `Target venue accommodating ${req.guestCount} guests with required amenities`,
      status: 'todo' as const,
      priority: 'critical' as const,
      dueDate: d1.toISOString().split('T')[0],
      estimatedCost: categories[0].allocatedAmount,
      actualCost: 0,
      dependencies: [],
    },
    {
      id: t2Id,
      eventId,
      name: `Finalize Menu Catering & Dietary Specifications (${req.culturalDietaryPreferences || 'Standard'})`,
      description: `Coordinate tasting session for ${req.guestCount} attendees`,
      status: 'todo' as const,
      priority: 'high' as const,
      dueDate: d2.toISOString().split('T')[0],
      estimatedCost: categories[1].allocatedAmount,
      actualCost: 0,
      dependencies: [t1Id], // Depends on securing venue
    },
    {
      id: t3Id,
      eventId,
      name: `Approve Theme & Decor Blueprint (${req.themeStyle || 'Curated Styling'})`,
      description: 'Review stage styling, entrance design, and floral arrangements',
      status: 'todo' as const,
      priority: 'medium' as const,
      dueDate: d3.toISOString().split('T')[0],
      estimatedCost: categories[2].allocatedAmount,
      actualCost: 0,
      dependencies: [t1Id],
    },
    {
      id: t4Id,
      eventId,
      name: 'Final Venue Inspection, Sound Check & Accessibility Ramp Verification',
      description: `Verify ${req.accessibilityRequirements || 'all accessibility features'} and on-site readiness`,
      status: 'todo' as const,
      priority: 'critical' as const,
      dueDate: d4.toISOString().split('T')[0],
      estimatedCost: 0,
      actualCost: 0,
      dependencies: [t2Id, t3Id], // Depends on both catering and decor
    },
  ];

  return {
    event: {
      id: eventId,
      name: req.name || `${req.location} ${req.eventType}`,
      eventType: req.eventType,
      eventDate: eventDateStr,
      location: req.location,
      budgetTotal: req.budgetTotal,
      currency: req.currency,
      guestCount: req.guestCount,
      themeStyle: req.themeStyle,
      culturalDietaryPreferences: req.culturalDietaryPreferences,
      accessibilityRequirements: req.accessibilityRequirements,
      specialRequirements: req.specialConstraints,
      isDemo: true,
    },
    categories,
    expenses: [],
    tasks,
    vendors: [],
    incidents: [],
    auditLogs: [
      {
        id: crypto.randomUUID(),
        eventId,
        action: 'PLAN_GENERATED_DETERMINISTIC',
        details: { req },
        timestamp: new Date().toISOString(),
      },
    ],
  };
}
